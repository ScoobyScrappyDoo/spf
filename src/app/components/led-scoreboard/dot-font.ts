/** Width of one character cell, in dots (5 dots and a gap). */
export const CELL = 6;
export const ROWS = 7;

export interface Dot {
  x: number;
  y: number;
  on: boolean;
}

/** Every dot of a text, lit and unlit, with the top-left corner at (x, y) and `pitch` units between dots. */
export function textDots(text: string, x: number, y: number, pitch = 1): Dot[] {
  const dots: Dot[] = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const glyph = GLYPHS[ch] ?? GLYPHS[' '] ?? Array(ROWS).fill('00000');
    for (let r = 0; r < ROWS; r++) {
      for (let c = 0; c < 5; c++) {
        dots.push({ x: x + (i * CELL + c) * pitch, y: y + r * pitch, on: glyph[r]?.[c] === '1' });
      }
    }
  });
  return dots;
}

/** How wide a text is, in units, at a given pitch (without the trailing gap). */
export const textWidth = (text: string, pitch = 1) => (text.length * CELL - 1) * pitch;
